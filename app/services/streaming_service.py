async def stream_chat_response(
    message: str,
    session_id: uuid.UUID,
    correlation_id: str,
    user_id: str,
    role: str,
    source: str,
):
    status = "failed"

    logger.info(
        "Chat stream started | correlation_id=%s | session_id=%s",
        correlation_id,
        session_id,
    )

    try:
        # 1. SESSION EVENT
        yield format_sse(
            "session",
            {
                "session_id": str(session_id),
                "correlation_id": correlation_id,
            },
        )

        # 2. TEMPORARY SAMPLE RESPONSE
        # Replace with orchestrator integration later.

        response_text = (
            "Here is the Greenz brochure you requested."
        )

        followup_chips = [
            "Show Greenz floor plans",
            "What is the Greenz payment plan?",
            "Show available Greenz units",
        ]

        brochure_url = (
            "https://example.com/greenz-brochure.pdf"
        )

        # 3. STREAM TEXT TOKENS
        for word in response_text.split(" "):
            yield format_sse(
                "token",
                {"text": word + " "},
            )

            await asyncio.sleep(0.1)

        # 4. HTML BLOCK
        # Sample HTML only. Replace the URL and HTML
        # with trusted marketing data later.

        html_content = f"""
        <div style="
            padding:20px;
            background:#1e1e1e;
            border-radius:12px;
            color:white;
            font-family:Arial;
        ">
            <h3>Greenz Brochure</h3>
            <p>Download the Greenz project brochure.</p>

            <a href="{brochure_url}"
               target="_blank"
               rel="noopener noreferrer"
               style="
                   display:inline-block;
                   padding:10px 18px;
                   background:#d4af37;
                   color:black;
                   text-decoration:none;
                   border-radius:6px;
               ">
                Download Brochure
            </a>
        </div>
        """

        html_event = HTMLBlockEvent(
            card_type="brochure",
            html=html_content,
        )

        yield format_sse(
            "html_block",
            html_event.model_dump(mode="json"),
        )

        # 5. FOLLOWUPS EVENT
        yield format_sse(
            "followups",
            {"chips": followup_chips},
        )

        # 6. FINAL EVENT
        final_response = ChatResponse(
            response=response_text,
            session_id=session_id,
            correlation_id=correlation_id,
            followups=followup_chips,
            data={
                "project": "Greenz",
                "files": [
                    {
                        "id": "greenz-brochure",
                        "name": "Greenz Brochure",
                        "type": "brochure",
                        "format": "pdf",
                        "download_url": brochure_url,
                    }
                ],
            },
        )

        yield format_sse(
            "final",
            final_response.model_dump(mode="json"),
        )

        status = "completed"

        logger.info(
            "Chat stream completed | correlation_id=%s | session_id=%s",
            correlation_id,
            session_id,
        )

    except asyncio.CancelledError:
        raise

    except Exception:
        logger.exception(
            "Chat stream failed | correlation_id=%s | session_id=%s",
            correlation_id,
            session_id,
        )
        error_response = ErrorResponse(
            error=ErrorDetail(
                code="STREAM_ERROR",
                message="An unexpected error occurred.",
                session_id=str(session_id),
                correlation_id=correlation_id,
                retryable=True,
            )
        )

        yield format_sse(
            "error",
            error_response.model_dump(mode="json"),
        )

    # 7. DONE EVENT
    # Only status is included, as requested.
    yield format_sse(
        "done",
        {"status": status},
    )
